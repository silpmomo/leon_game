def rows(w, *lines):
    for i, ln in enumerate(lines):
        assert len(ln) == w, f'{i}행 길이 {len(ln)} != {w}: {ln!r}'
    return list(lines)


def dump(name, w, h, palette, frames, frame_names):
    assert len(frames) == len(frame_names), f'{name}: 프레임 수 불일치'
    for fi, f in enumerate(frames):
        assert len(f) == h, f'{name} 프레임 {fi} 행 수 {len(f)} != {h}'
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f'{name}.json')
    with open(path, 'w', encoding='utf-8') as fp:
        json.dump(
            {'name': name, 'w': w, 'h': h, 'palette': palette,
             'frameNames': frame_names, 'frames': frames},
            fp, indent=1, ensure_ascii=False,
        )
        fp.write('\n')
    print(f'  {name}.json  {w}x{h} x{len(frames)}프레임')


