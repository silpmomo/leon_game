def ball(spots):
    base = rows(
        12,
        '000044440000',
        '004444444400',
        '044444444440',
        '044444444440',
        '444444444444',
        '444444444444',
        '444444444444',
        '444444444444',
        '044444444440',
        '044444444440',
        '004444444400',
        '000044440000',
    )
    out = []
    for y, ln in enumerate(base):
        chars = list(ln)
        for (sx, sy) in spots:
            if sy == y and chars[sx] == '4':
                chars[sx] = '5'
        out.append(''.join(chars))
    return rows(12, *out)


