def bolt_block(lit):
    """전기 블록. lit 이면 번개가 밝게 빛난다.

    안쪽 14칸에 번개 지그재그를 그린다. 각 행은 (앞 여백, 번개 폭) 으로 적고
    나머지를 채워 폭 14를 맞춘다 — 손으로 세다가 어긋나는 것을 막는다.
    """
    b = '4' if lit else '5'
    z = '1' if lit else '3'
    # (앞 여백, 번개 폭)
    glyph = [
        (0, 0), (6, 2), (5, 2), (4, 2), (3, 4),
        (4, 3), (5, 2), (6, 2), (5, 2), (4, 2),
        (5, 2), (6, 2), (7, 1), (0, 0),
    ]
    out = ['3' * 16]
    for pad, n in glyph:
        inner = b * pad + z * n + b * (14 - pad - n)
        assert len(inner) == 14, f'번개 행 폭 {len(inner)}'
        out.append('3' + inner + '3')
    out.append('3' * 16)
    return rows(16, *out)


