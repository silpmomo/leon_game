def coin(w_cols):
    """w_cols: 반짝임 폭 (10, 6, 2, 6) 로 회전 흉내"""
    pad = (10 - w_cols) // 2
    body = []
    for y in range(14):
        if y in (0, 13):
            body.append('0' * 10)
            continue
        inner = '6' * w_cols
        if 3 <= y <= 6 and w_cols >= 6:
            inner = '6' * (w_cols // 2 - 1) + '77' + '6' * (w_cols - w_cols // 2 - 1)
        line = '0' * pad + inner + '0' * (10 - pad - w_cols)
        body.append(line)
    return rows(10, *body)


