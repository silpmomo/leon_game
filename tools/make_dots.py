def lava_frame(shift):
    top = []
    for x in range(16):
        top.append('7' if (x + shift) % 5 == 0 else '4')
    body = []
    for y in range(1, 16):
        line = ''
        for x in range(16):
            v = (x + y * 2 + shift) % 7
            line += '5' if v < 4 else '6'
        body.append(line)
    return rows(16, ''.join(top), *body)


