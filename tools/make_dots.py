def solid_tile(a, b, edge):
    out = [edge * 16]
    for y in range(1, 16):
        line = ''
        for x in range(16):
            line += a if ((x // 4) + (y // 4)) % 2 == 0 else b
        out.append(line)
    return rows(16, *out)


